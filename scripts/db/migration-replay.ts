/**
 * #434 Slice C: replay EVERY migration from an empty database and compare the result with the schema the dev and test
 * path builds (pre-push.sql, `prisma db push`, post-push.sql), so a structural object that drifted between the two (the
 * class that has bitten: an `IF NOT EXISTS` object whose definition changed in a migration but stayed stale in
 * post-push.sql) fails CI.
 *
 * - REPLAY: an empty database, then `prisma migrate deploy` of the full history and nothing else (a migration creates the
 *   vector extension itself).
 * - REFERENCE: an empty database built by `buildTestSchema`, the test templates' own path.
 * - The comparison is the pg_catalog snapshot Slice A's parity test uses (src/test/catalogSnapshot.ts), never a text dump.
 *
 * Today the two are NOT equal, so the differences on main are a checked-in, SHRINK-ONLY baseline
 * (scripts/db/migration-replay-baseline.txt; Xan's gate ruling (c) on #434). The check fails on any difference not in the
 * baseline (new drift) AND on any baseline entry that no longer differs (a fix must delete its line). The baseline is
 * never regenerated by this script; `--print` only prints the current differences for a reviewer.
 *
 * Usage: MIGRATION_REPLAY_ADMIN_URL=postgresql://user@host:5432/postgres pnpm tsx scripts/db/migration-replay.ts [--print]
 * The admin URL needs CREATEDB; the two scratch databases are created from template0 and dropped afterwards.
 *
 * Exit codes: 0 clean; 1 a DETECTION (new drift, a stale line, unapproved growth); 2 an OPERATIONAL failure (missing
 * configuration, a malformed baseline line, a scratch database that could not be dropped, any crash) (#4378 item 1).
 * Environment: MIGRATION_REPLAY_ADMIN_URL, MIGRATION_REPLAY_BASE_BASELINE, MIGRATION_REPLAY_ALLOW_GROWTH (#4378 item 7).
 */
import { execFile } from 'node:child_process';
import { createHash, randomBytes } from 'node:crypto';
import { existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';
import { Client } from 'pg';
import { differenceKind, snapshot, type Snapshot } from '../../src/test/catalogSnapshot.js';
import { buildTestSchema } from '../../src/test/schemaTemplate.js';

const execFileAsync = promisify(execFile);
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const BASELINE_PATH = join(ROOT, 'scripts/db/migration-replay-baseline.txt');

/**
 * The baseline's entries: one `<added|removed|changed|reformatted> <object key> <fingerprint>` per line; `#` comments and
 * blanks skipped. The key may contain spaces (a routine's signature, `fn:f(x integer, y text)`), so a line is read as
 * kind up to the FIRST space and fingerprint after the LAST (#4338 BLIND F2). The fingerprint pins BOTH definitions, so a
 * baselined object that drifts again, or whose drift grows, no longer matches its line and fails as new drift.
 */
export function parseBaseline(text: string): string[] {
  const entries: string[] = [];
  text.split('\n').forEach((raw, i) => {
    const line = raw.trim();
    if (!line || line.startsWith('#')) return;
    // #4378 item 8: a line that is not an entry is refused here (an operational failure, exit 2), naming it, instead of
    // reaching the judge and surfacing only indirectly as a stale line.
    if (!BASELINE_LINE.test(line)) throw new BaselineFormatError(`line ${i + 1}: ${line}`);
    entries.push(line);
  });
  return entries;
}

/** `<kind> <object kind>:<non-empty key> <16 lowercase hex>`; the key may hold spaces (and escapes, `encodeKey`). */
const BASELINE_LINE = /^(added|removed|changed|reformatted) (col|con|idx|fn|seq|view|tg):\S.* [0-9a-f]{16}$/;

/** A baseline line that is not an entry: the file is wrong, which is an operational failure, not drift. */
export class BaselineFormatError extends Error {
  constructor(where: string) {
    super(`malformed baseline line (expected '<added|removed|changed|reformatted> <col|con|idx|fn|seq|view|tg>:<key> <16 hex>'), ${where}`);
    this.name = 'BaselineFormatError';
  }
}

/** A short, stable fingerprint of a difference's two definitions (the reference's, then the replay's; '' when absent). */
export function fingerprint(reference: string | undefined, replay: string | undefined): string {
  return createHash('sha256').update(`${reference ?? ''}\u0000${replay ?? ''}`).digest('hex').slice(0, 16);
}

/** One line per entry: a key's backslash and control characters (a quoted identifier may hold a newline) are escaped. */
export function encodeKey(key: string): string {
  return key.replace(/\\/g, '\\\\').replace(/\n/g, '\\n').replace(/\r/g, '\\r').replace(/\t/g, '\\t');
}

/**
 * The migration engine's own bookkeeping, which exists only on the replay by construction: the EXACT relation
 * `_prisma_migrations` (its columns, constraints and triggers) and its primary-key index. Nothing that merely starts with
 * that name (an application table `_prisma_migrations_archive`) is skipped (#4338 BLIND F3).
 */
export function isEngineBookkeeping(key: string): boolean {
  return /^(col|con|tg):_prisma_migrations\./.test(key) || key === 'idx:_prisma_migrations_pkey';
}

/**
 * Each catalog difference as its baseline entry, `<kind> <encoded key> <fingerprint>`, with both definitions in
 * `details`. Built from the two snapshots directly, so kind, key and definitions stay structured until serialization
 * (#4338 BLIND F2, F6). The kind is `differenceKind`'s, the same decision catalogSnapshot.diff makes: `added` exists only
 * on the replay, `removed` only on the reference, a function differing only in SQL whitespace is `reformatted`.
 */
export function differenceEntries(reference: Snapshot, replay: Snapshot): { entries: string[]; details: Map<string, string> } {
  const details = new Map<string, string>();
  for (const key of [...new Set([...reference.keys(), ...replay.keys()])].sort()) {
    const before = reference.get(key);
    const after = replay.get(key);
    const kind = differenceKind(key, before, after); // the ONE kind decision, shared with catalogSnapshot.diff (#4378 item 5)
    if (kind === null || isEngineBookkeeping(key)) continue;
    details.set(`${kind} ${encodeKey(key)} ${fingerprint(before, after)}`,
      `  push + post-push: ${before ?? '(absent)'}\n  migration replay: ${after ?? '(absent)'}`);
  }
  return { entries: [...details.keys()].sort(), details };
}

/**
 * Entries the PR's baseline adds over the base branch's (#4338 BLIND F1): the check itself enforces shrink-only, not
 * just review. Growth fails unless the change manager approved it on the PR (the `baseline-growth-approved` label, which
 * the workflow turns into MIGRATION_REPLAY_ALLOW_GROWTH=true).
 */
export function baselineGrowth(prBaseline: string[], baseBaseline: string[]): string[] {
  const base = new Set(baseBaseline);
  return prBaseline.filter((e) => !base.has(e));
}

/**
 * Shrink-only judgement. `unexpected`: a difference the baseline does not list (new drift, or a line deleted while its
 * difference is still present). `stale`: a baseline line whose difference is gone (fixed: delete the line). A duplicate
 * baseline line is stale too, so the file cannot hide growth behind repetition.
 */
export function judge(entries: string[], baseline: string[]): { unexpected: string[]; stale: string[] } {
  const present = new Set(entries);
  const listed = new Set<string>();
  const stale: string[] = [];
  for (const b of baseline) {
    if (listed.has(b) || !present.has(b)) stale.push(b);
    listed.add(b);
  }
  return { unexpected: entries.filter((e) => !listed.has(e)), stale };
}

/**
 * The run's outcome from its differences, as data (#4378 item 8): `--print` lists the entries and judges nothing;
 * otherwise new drift and stale lines are detections, and growth over the base branch's baseline is one unless approved.
 * `baseBaseline` undefined means the base has no baseline yet (the bootstrapping PR): growth is not judged.
 */
export function evaluate(args: {
  entries: string[]; details: Map<string, string>; print: boolean;
  baseline: string[] | undefined; baseBaseline: string[] | undefined; allowGrowth: boolean;
}): { code: 0 | 1; out: string[]; err: string[] } {
  const { entries, details } = args;
  if (args.print) return { code: 0, out: [...entries], err: [] };
  const baseline = args.baseline ?? [];
  const { unexpected, stale } = judge(entries, baseline);
  const growth = args.baseBaseline === undefined ? [] : baselineGrowth(baseline, args.baseBaseline);
  const err = [
    // The entry first (with its fingerprint, exactly as a baseline line would carry it), then both definitions.
    ...unexpected.map((u) => `NEW DRIFT (not in the baseline): ${u}\n${details.get(u) ?? ''}`),
    ...stale.map((x) => `STALE BASELINE LINE (no longer differs, or duplicated; delete it): ${x}`),
    ...growth.map((g) => `${args.allowGrowth ? 'APPROVED BASELINE GROWTH' : 'BASELINE GROWTH (not on the base branch; needs the change manager\'s baseline-growth-approved label)'}: ${g}`),
  ];
  const out = [`migration replay: ${entries.length} difference(s) from push + post-push; baseline lists ${entries.length - unexpected.length}.`];
  return { code: unexpected.length || stale.length || (growth.length && !args.allowGrowth) ? 1 : 0, out, err };
}

/**
 * The process exit code (#4378 item 1): a scratch database left behind is an OPERATIONAL failure (2), so a clean run
 * that leaked exits 2, never the detection code 1; a run that also detected drift still reports the detection (1).
 */
export function exitCode(code: number, cleanupFailures: number): number {
  return cleanupFailures > 0 && code === 0 ? 2 : code;
}

const quote = (name: string) => `"${name.replace(/"/g, '""')}"`;
/** The same server, user and query string (sslmode and the rest), with only the database path replaced. */
export const withDb = (url: string, name: string) => { const u = new URL(url); u.pathname = `/${name}`; return u.toString(); };

/**
 * Drop each scratch database independently and report a failure by name (#4338 BLIND F3): a run that leaves one behind
 * fails, so a green check never hides a leak. Returns the names that could not be dropped.
 */
export async function dropScratch(
  query: (sql: string) => Promise<unknown>, dbs: string[], log: (line: string) => void,
): Promise<string[]> {
  const failed: string[] = [];
  for (const db of dbs) {
    try { await query(`DROP DATABASE IF EXISTS ${quote(db)} WITH (FORCE)`); }
    catch (e) { failed.push(db); log(`CLEANUP FAILED: could not drop scratch database ${db}: ${(e as Error).message}`); }
  }
  return failed;
}

/**
 * #4395 item 1: a reader that closes the pipe early (`--print | head`) makes the next write fail with EPIPE, and an
 * unhandled stream error kills the process before the `finally` drops the scratch databases. A closed reader only
 * means nobody reads the rest: EPIPE is swallowed (later writes go nowhere) and any other stream error still crashes.
 */
export function ignoreClosedPipe(stream: NodeJS.WriteStream): void {
  stream.on('error', (e: NodeJS.ErrnoException) => { if (e.code !== 'EPIPE') throw e; });
}

const cleanupFailed: string[] = [];

async function main(): Promise<number> {
  const adminUrl = process.env.MIGRATION_REPLAY_ADMIN_URL;
  if (!adminUrl) { console.error('MIGRATION_REPLAY_ADMIN_URL is required (a maintenance-database URL with CREATEDB).'); return 2; }
  const print = process.argv.includes('--print');
  // Both baselines are read and validated BEFORE any scratch database exists, so a malformed line fails fast (exit 2).
  let baseline: string[] | undefined;
  let baseBaseline: string[] | undefined;
  try {
    if (!print) baseline = parseBaseline(readFileSync(BASELINE_PATH, 'utf8'));
    const basePath = process.env.MIGRATION_REPLAY_BASE_BASELINE;
    if (!print && basePath) {
      if (existsSync(basePath)) baseBaseline = parseBaseline(readFileSync(basePath, 'utf8'));
      else console.log('migration replay: the base has no baseline yet (the bootstrapping change); growth not judged.');
    }
  } catch (e) {
    if (e instanceof BaselineFormatError) { console.error(e.message); return 2; }
    throw e;
  }
  const tag = `${process.pid}_${randomBytes(4).toString('hex')}`;
  const replayDb = `hadron_replay434_${tag}`;
  const refDb = `hadron_replayref434_${tag}`;
  const admin = new Client({ connectionString: adminUrl });
  await admin.connect();
  let r: ReturnType<typeof evaluate>;
  try {
    for (const db of [replayDb, refDb]) await admin.query(`CREATE DATABASE ${quote(db)} TEMPLATE template0`);
    const replayUrl = withDb(adminUrl, replayDb);
    const refUrl = withDb(adminUrl, refDb);
    await execFileAsync(join(ROOT, 'node_modules/.bin/prisma'), ['migrate', 'deploy'], {
      cwd: ROOT, env: { ...process.env, DATABASE_URL: replayUrl }, maxBuffer: 64 * 1024 * 1024,
    });
    await buildTestSchema(refUrl, ROOT);
    const snap = async (url: string) => {
      const c = new Client({ connectionString: url });
      await c.connect();
      try { return await snapshot(c); } finally { await c.end(); }
    };
    // before = the reference (push + post-push), after = the replay: `added` exists only on the migration path.
    const reference = await snap(refUrl);
    const replay = await snap(replayUrl);
    const { entries, details } = differenceEntries(reference, replay);
    r = evaluate({ entries, details, print, baseline, baseBaseline, allowGrowth: process.env.MIGRATION_REPLAY_ALLOW_GROWTH === 'true' });
  } finally {
    cleanupFailed.push(...await dropScratch((sql) => admin.query(sql), [replayDb, refDb], (line) => console.error(line)));
    await admin.end().catch(() => {});
  }
  // #4395 item 1: the result is written only once the scratch databases are gone, so no write can race the cleanup.
  for (const line of r.out) console.log(line);
  for (const line of r.err) console.error(line);
  return r.code;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  ignoreClosedPipe(process.stdout);
  ignoreClosedPipe(process.stderr);
  main().then((code) => process.exit(exitCode(code, cleanupFailed.length)), (e) => { console.error(e); process.exit(2); });
}
