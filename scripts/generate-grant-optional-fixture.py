def jstr(s):
    out = ['"']
    short = {'"': '\\"', '\\': '\\\\', '\b': '\\b', '\f': '\\f', '\n': '\\n', '\r': '\\r', '\t': '\\t'}
    for ch in s:
        if ch in short:
            out.append(short[ch])
        elif ord(ch) < 0x20:
            out.append('\\u%04x' % ord(ch))
        else:
            out.append(ch)
    out.append('"')
    return ''.join(out)


def jobject(d):
    assert all(k and all(0x21 <= ord(c) <= 0x7e and c not in '"' + chr(92) for c in k) for k in d), d
    assert all(isinstance(v, str) and v != '' for v in d.values()), d
    return '{' + ','.join(jstr(k) + ':' + jstr(d[k]) for k in sorted(d)) + '}'


