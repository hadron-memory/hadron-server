"""Generate pinned Unicode 16 tables; pass confusables.txt and CaseFolding.txt paths.

Sources: https://www.unicode.org/Public/security/16.0.0/confusables.txt
         https://www.unicode.org/Public/16.0.0/ucd/CaseFolding.txt
License: src/lib/unicode/LICENSE.txt. No runtime download or third-party package.
"""
import hashlib
import json
from pathlib import Path
import sys

SOURCES = [
    ('CONFUSABLES', '95bd0aad6dced5ebc63436f459c06ab21a8d107cd842fb57f5c3a1e91bca8611'),
    ('CASE_FOLD', '6f1f9c588eb4a5c718d9e8f93b782685e5c7fec872cf05e8e6878053599e09bb'),
]
output = ['// Generated by scripts/generate-worker-name-data.py; Unicode 16.0.0.',
          '// Copyright Unicode, Inc.; see unicode/LICENSE.txt. Do not edit by hand.']
for (name, digest), arg in zip(SOURCES, sys.argv[1:], strict=True):
    raw = Path(arg).read_bytes()
    assert hashlib.sha256(raw).hexdigest() == digest, f'Wrong source for {name}'
    rows = {}
    for line in raw.decode('utf-8').splitlines():
        line = line.split('#', 1)[0].strip()
        if not line:
            continue
        fields = [field.strip() for field in line.split(';')]
        if name == 'CONFUSABLES':
            source, target, status = fields[:3]
            assert status == 'MA' and len(source.split()) == 1
        else:
            source, status, target = fields[:3]
            if status not in ('C', 'F'):  # full, locale-independent folding
                continue
        rows[int(source, 16)] = ''.join(chr(int(cp, 16)) for cp in target.split())
    output += [f'// Source SHA-256: {digest}',
               f'export const {name}: ReadonlyMap<number, string> = new Map([']
    output += [f'  [0x{cp:X}, {json.dumps(value, ensure_ascii=True)}],' for cp, value in sorted(rows.items())]
    output += [']);', '']
destination = Path(__file__).resolve().parents[1] / 'src/lib/unicode/workerNameData.ts'
destination.parent.mkdir(parents=True, exist_ok=True)
destination.write_text('\n'.join(output), encoding='utf-8')
