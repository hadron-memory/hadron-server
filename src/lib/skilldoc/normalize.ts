/**
 * #1177 — the normalization the skill hash is computed over.
 *
 * This is the file A2 lives in. `Hash` is recomputable from a skill file alone,
 * which is what makes a local edit detectable — and that only works if this
 * normalization agrees with the Go implementation to the byte. @Eli measured
 * exactly where a naive port diverges, and both divergences are here.
 *
 * ## Why `String.prototype.trim()` is the wrong function
 *
 * `strings.TrimSpace` trims Unicode **White_Space**. JS `.trim()` trims
 * `WhiteSpace ∪ LineTerminator`, which is White_Space **plus U+FEFF minus
 * U+0085** — two code points, divergent in OPPOSITE directions:
 *
 * | code point | Go TrimSpace | JS .trim() | |
 * |---|---|---|---|
 * | U+0085 NEL | trims | does **not** | JS under-trims |
 * | U+FEFF ZWNBSP | does **not** | trims | JS over-trims |
 *
 * Neither is hypothetical: a description pasted from a Word document or a web
 * page is exactly where U+00A0 and U+FEFF arrive, and U+FEFF leads any file
 * saved with a BOM.
 *
 * A divergence here does not fail loudly. It makes a freshly exported file
 * hash differently from the node it was rendered from, so every skill reads as
 * drifted — which is why the fixtures carry expected values generated BY the
 * Go implementation rather than by a second reading of the spec.
 */

/**
 * Unicode `White_Space`, which is exactly what Go's `unicode.IsSpace` tests.
 * Written out rather than expressed as a regex class because the point is that
 * this set is NOT the one any JS built-in uses — a reader comparing it against
 * `\s` or `.trim()` should see the difference rather than have to trust it.
 */
const GO_WHITE_SPACE = new Set<number>([
  0x09, 0x0a, 0x0b, 0x0c, 0x0d, // TAB LF VT FF CR
  0x20, // SPACE
  0x85, // NEL — trimmed by Go, NOT by JS .trim()
  0xa0, // NBSP
  0x1680, // OGHAM SPACE MARK
  0x2000, 0x2001, 0x2002, 0x2003, 0x2004, 0x2005,
  0x2006, 0x2007, 0x2008, 0x2009, 0x200a,
  0x2028, // LINE SEPARATOR
  0x2029, // PARAGRAPH SEPARATOR
  0x202f, // NARROW NO-BREAK SPACE
  0x205f, // MEDIUM MATHEMATICAL SPACE
  0x3000, // IDEOGRAPHIC SPACE
  // U+FEFF is deliberately ABSENT: JS .trim() removes it and Go does not.
]);

/** Count CODE POINTS, as Go's `utf8.RuneCountInString` does — not UTF-16 units.
 *
 * `"a👍b".length` is 4 in JS and 3 in Go, because an astral character is a
 * surrogate pair. Every cap in this contract (64 for a name, 1024 for a
 * description) is the host's, counted in code points, so `.length` is wrong for
 * any string containing an emoji — and an emoji in a trigger phrase is not
 * hypothetical. */
export function runeCount(s: string): number {
  let n = 0;
  for (const _ of s) n += 1;
  return n;
}

/** Go's `strings.TrimSpace`, not JS's `.trim()`. See the header. */
export function goTrimSpace(s: string): string {
  const cps = [...s];
  let start = 0;
  let end = cps.length;
  while (start < end && GO_WHITE_SPACE.has(cps[start]!.codePointAt(0)!)) start += 1;
  while (end > start && GO_WHITE_SPACE.has(cps[end - 1]!.codePointAt(0)!)) end -= 1;
  return cps.slice(start, end).join('');
}

/**
 * The description as exported: surrounding whitespace trimmed.
 *
 * Lint measures this and `render` writes it, so the length a rule certifies is
 * the length the host sees — a description with a trailing space is not 1025
 * characters on disk.
 */
export function normalizeDescription(s: string): string {
  return goTrimSpace(s);
}

/**
 * The body as exported: CRLF folded to LF, then leading and trailing newlines
 * trimmed.
 *
 * Trims **only** `\n`, which is why none of the whitespace divergences above
 * reach it — and why a lone `\r` survives. The CRLF fold must not become a
 * general newline normalization: `\r` alone is preserved today and a port that
 * "tidied" that would change the hash of every body containing one.
 *
 * Spaces are NOT trimmed here, unlike the description. The two normalizations
 * are deliberately different and a shared helper would be the bug.
 */
export function normalizeBody(s: string): string {
  const folded = s.replace(/\r\n/g, '\n');
  let start = 0;
  let end = folded.length;
  while (start < end && folded[start] === '\n') start += 1;
  while (end > start && folded[end - 1] === '\n') end -= 1;
  return folded.slice(start, end);
}
