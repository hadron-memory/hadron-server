/**
 * #1177 — composing a skill file.
 *
 * YAML frontmatter with the two keys a host reads, the machine-parseable
 * provenance line, the human note, then the node body NORMALIZED — the same
 * form `hash` fingerprints and `parseFile` reads back.
 *
 * ## Frontmatter goes through a real YAML encoder, never hand-quoting
 *
 * A description ending in a colon, or in a space, is a plain scalar that a hand
 * check would pass and a real parser would reject or trim — and the host
 * reading this file IS a real parser. Exactly two keys, in this order, so the
 * file looks like every hand-written skill on disk.
 *
 * ## Render is NOT byte-identical to the Go implementation, and it does not
 * ## have to be — a refinement to @Eli's A2
 *
 * A2 says the port is "byte-compatible with the Go implementation". That is
 * required of `hash` and impossible for `render`: Go's `yaml.v3` emits
 * `'use when:'` and the JS `yaml` package emits `"use when:"` for the same
 * value. Measured, not assumed.
 *
 * It does not matter, and the reason is structural rather than lucky: the hash
 * covers the raw source, name, description and body — it never sees the
 * rendered frontmatter — so quoting style cannot move it. Both spellings parse
 * back to the same string, so `parseFile` and the host agree too.
 *
 * What that leaves is a file whose BYTES differ from one a Go export would have
 * written. Under this port only the server renders, so there is no second
 * renderer to disagree with; and every file currently on disk carries a legacy
 * header and is due a rewrite regardless (all 20 measured — none has a hash).
 *
 * So render parity is SEMANTIC and hash parity is BYTE-EXACT, and the fixtures
 * assert them differently on purpose.
 */

import { stringify } from 'yaml';
import { hash } from './hash.js';
import { isNodeUrn } from './parse.js';
import { normalizeBody, normalizeDescription } from './normalize.js';

/** The human note a generated file carries. Prose — nothing parses it. */
export const HUMAN_LINE =
  '<!-- Generated by `hadron skill export`. Edit the source node and re-export; do not edit this file. -->';

/** The pre-#580 human note, still on files written by the hand-run procedure. */
export const LEGACY_HUMAN_LINE =
  '<!-- Edit the source node and re-export; do not edit this file directly. -->';

/** A source that cannot be written into a provenance comment safely. */
export class SkillRenderError extends Error {}

/**
 * The characters a legitimate flat-v2 node URN can contain: `hrn:node:` plus a
 * loc whose segments satisfy spec 021 FR-016 (`[a-zA-Z0-9._-]`), colon-joined.
 *
 * Written as an ALLOW-list rather than a ban-list of `-->` (@copilot round 3,
 * PR #1223). The first version refused the comment terminator and nothing else,
 * which left the same hole open one character over: a source containing a
 * NEWLINE ends the header line, and everything after it is body — the identical
 * outcome by a different route. Banning the exploit I had been shown, rather
 * than admitting only what is valid, is the mistake the ban-list encodes.
 *
 * An allow-list also closes the space case reported earlier in this PR — a
 * space-bearing source renders in Go and then cannot be parsed back, pairing
 * nothing. Refusing to write it is better than writing a file that silently
 * orphans itself.
 */
const SAFE_SOURCE_RE = /^[A-Za-z0-9._:-]+$/;

/**
 * Compose the skill file.
 *
 * `content` and `description` are normalized here, so a caller cannot produce a
 * file whose body disagrees with the hash in its own header.
 *
 * ## The one DELIBERATE divergence from the Go reference (@copilot, PR #1223)
 *
 * `source` is interpolated into an HTML comment. A source containing `-->`
 * closes that comment early, and everything after it becomes visible skill
 * BODY — which a host reads as instructions to an agent. Go interpolates it
 * unescaped too, so this refusal is behaviour the reference does not have.
 *
 * It is taken anyway, and the reachability is why: the API-layer write paths
 * run `validateLoc` (11 call sites), whose charset excludes `>` — but **git
 * sync derives a loc from the FILE PATH and never validates it**. A mirrored
 * repo containing a file named with `-->` mints exactly such a loc. So the
 * invariant that makes unescaped interpolation safe is enforced by a different
 * writer than the one that can break it: safe AND fragile, the shape
 * `findings:org-xor-owner-null-comparison-bypass` names.
 *
 * REFUSING rather than escaping is deliberate. Escaping would change the file
 * format and need a matching decode on both sides; a refusal changes nothing
 * for any input the format was ever meant to carry, and turns an injected
 * instruction into a loud error. The broader gap — git sync writing unvalidated
 * locs, which is not a skills problem — is reported separately.
 */
export function render(name: string, source: string, description: string, content: string): string {
  // BOTH: the charset a one-line comment can carry, AND the shape the parser
  // will accept back (@copilot round 4). Charset alone still let `render` write
  // a header `parseFile` refuses as not-ours — the file would orphan itself and
  // a re-export would write a second copy beside it. Render and parse are
  // inverses or they are not; this is the half that makes that true in the
  // write direction.
  if (!SAFE_SOURCE_RE.test(source) || !isNodeUrn(source)) {
    throw new SkillRenderError(
      `skill source URN contains characters that cannot be written into a one-line ` +
        `provenance comment; the remainder of the header would become agent-visible ` +
        `instructions: ${JSON.stringify(source)}`,
    );
  }
  const d = normalizeDescription(description);
  const c = normalizeBody(content);
  // Two keys, in this order. `stringify` ends with a newline; the framing below
  // supplies its own, so it is trimmed rather than doubled.
  const fm = stringify({ name, description: d }).replace(/\n+$/, '');
  const h = hash(source, name, d, c);
  return (
    '---\n' +
    fm +
    '\n---\n\n' +
    `<!-- hadron-skill source=${source} hash=${h} -->\n` +
    HUMAN_LINE +
    '\n\n' +
    c +
    '\n'
  );
}
